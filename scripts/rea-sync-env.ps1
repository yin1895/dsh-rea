# D:\REA-tool\bin\rea-sync-env.ps1
# Regenerate config\rea.env.cmd from config\rea.env.json so cmd.exe sessions and
# PowerShell sessions always agree. Run it after editing the JSON.
$ErrorActionPreference = 'Stop'

$home_ = 'D:\REA-tool'
$json  = Join-Path $home_ 'config\rea.env.json'
$cmd   = Join-Path $home_ 'config\rea.env.cmd'

$cfg = Get-Content $json -Raw | ConvertFrom-Json

$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('@echo off')
$lines.Add('REM D:\REA-tool\config\rea.env.cmd - generated by bin\rea-sync-env.ps1 from config\rea.env.json.')
$lines.Add('REM Put every REA engine on PATH and set the REA_* / GHIDRA_INSTALL_DIR variables for this cmd session.')
foreach ($p in $cfg.variables.PSObject.Properties) {
    $lines.Add(('set "{0}={1}"' -f $p.Name, [string]$p.Value))
}
$lines.Add(('set "REA_TOOL_HOME={0}"' -f $cfg.home))
$lines.Add(('set "REA_MCP_NODE={0}"' -f $cfg.node))
$lines.Add(('set "PATH={0};%PATH%"' -f ((@($cfg.pathPrepend)) -join ';')))

Set-Content -Path $cmd -Value $lines -Encoding ascii
"wrote $cmd ($($lines.Count) lines)"
